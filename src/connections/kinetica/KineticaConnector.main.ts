import type { QueryResponseType, Table } from '../../types/backend';
import { ConnectionDbt } from '../core/ConnectionDbt.main';
import type { ProfileImportContext } from '../core/ConnectionDbt.main';
import type { QueryContext, TestResult } from '../core/Connection.main';
import type { AgentHintContext } from '../core/agentHints.main';
import {
  kineticaDescriptor,
  type KineticaConnection,
  type KineticaDBTConnection,
} from './kinetica.shared';
import {
  executeKineticaQuery,
  testKineticaConnection,
} from './kinetica.client.main';
import KineticaExtractor from './kinetica.extractor.main';
import {
  buildKineticaProfileOutput,
  DEFAULT_KINETICA_SCHEMA,
} from './kinetica.profile.main';
import { buildKineticaUrl, parseKineticaUrl } from './kinetica.url.shared';

export class KineticaConnector extends ConnectionDbt<
  KineticaConnection,
  KineticaDBTConnection
> {
  readonly descriptor = kineticaDescriptor;

  readonly dbtAdapterType = 'kinetica';

  // CS validateConnection (1302-1305)
  async validate(conn: KineticaConnection): Promise<void> {
    if (!conn.host) throw new Error('Host is required');
    if (!conn.port) throw new Error('Port is required');
  }

  // CS testConnection (925-926)
  test(conn: KineticaConnection): Promise<TestResult> {
    return testKineticaConnection(conn);
  }

  // CS executeSelectStatement (1125-1131)
  query(
    conn: KineticaConnection,
    sql: string,
    ctx: QueryContext,
  ): Promise<QueryResponseType> {
    return executeKineticaQuery(conn, sql, ctx.onCancelable);
  }

  // CS extractSchemaFromConnection (2369-2387), `kinConn` -> `conn`
  async extractSchema(conn: KineticaConnection): Promise<{ tables: Table[] }> {
    const extractor = new KineticaExtractor({
      host: conn.host,
      port: conn.port,
      username: conn.username,
      password: conn.password,
      useSSL: conn.useSSL,
      timeout: conn.timeout,
      schema: conn.schema,
    });
    try {
      await extractor.connect();
      const schema = await extractor.extractSchema();
      return schema;
    } finally {
      await extractor.disconnect();
    }
  }

  // CS areConnectionConfigsEqual (305-324)
  sameTarget(a: KineticaConnection, b: KineticaConnection): boolean {
    return (
      a.host === b.host &&
      a.port === b.port &&
      a.useSSL === b.useSSL &&
      a.database === b.database &&
      a.username === b.username &&
      a.schema === b.schema &&
      a.timeout === b.timeout &&
      a.bypassSslCertCheck === b.bypassSslCertCheck
    );
  }

  // CS generateUniqueConnectionName (410-412)
  nameHint(conn: KineticaConnection): string {
    return conn.database || 'kinetica';
  }

  // sqlAgent.ts 96-99; identical in the three agents
  agentHint(_ctx: AgentHintContext): string {
    return '\n\n## Dialect Specifics\nYou are connected to Kinetica. Ensure all queries use Kinetica SQL syntax and functions.';
  }

  // CS mapToDbtConnection (1498-1510)
  toDbtConnection(conn: KineticaConnection): KineticaDBTConnection {
    return {
      type: 'kinetica',
      host: conn.host,
      port: conn.port,
      username: `db-user-${conn.name}`,
      password: `db-password-${conn.name}`,
      database: conn.database,
      schema: conn.schema || DEFAULT_KINETICA_SCHEMA,
      timeout: conn.timeout,
      useSSL: conn.useSSL,
      bypassSslCertCheck: conn.bypassSslCertCheck,
    };
  }

  // CS mapToDbtProfileOutput (1687-1688)
  async toProfileOutput(
    conn: KineticaConnection,
  ): Promise<Record<string, unknown>> {
    return buildKineticaProfileOutput(conn, (field: string) =>
      this.profileRef(conn, field),
    );
  }

  // CS parseProfilesYml (1846-1869), `this.resolveExactEnvVar` -> `ctx.resolveEnvVar`
  fromProfileOutput(
    devOutput: Record<string, any>,
    ctx: ProfileImportContext,
  ): KineticaDBTConnection {
    // dbt-kinetica accepts `host` (alias `url`) as a full URL and
    // `user`/`username`, `password`/`pass`, `database`/`dbname` aliases.
    // Profiles generated by the Studio store the URL as an env_var
    // placeholder (`db-url-<connection>`), so resolve it first.
    const kineticaUrl = parseKineticaUrl(
      String(
        ctx.resolveEnvVar(devOutput.host ?? devOutput.url) ??
          'http://localhost:9191',
      ),
    );
    return {
      type: 'kinetica',
      host: kineticaUrl.host,
      port: kineticaUrl.port,
      useSSL: kineticaUrl.useSSL,
      bypassSslCertCheck: devOutput.skip_ssl_cert_verification === true,
      username: devOutput.user ?? devOutput.username ?? '',
      password: devOutput.password ?? devOutput.pass ?? '',
      database: devOutput.database ?? devOutput.dbname ?? '',
      schema: devOutput.schema || DEFAULT_KINETICA_SCHEMA,
    };
  }

  // CS mapDBTConnectionToConnectionInput (1975-1989)
  toConnectionInput(
    dbtConnection: KineticaDBTConnection,
    connectionName: string,
  ): KineticaConnection {
    return {
      type: 'kinetica',
      name: connectionName,
      host: dbtConnection.host,
      port: dbtConnection.port,
      username: dbtConnection.username,
      password: dbtConnection.password,
      database: dbtConnection.database,
      schema: dbtConnection.schema,
      timeout: dbtConnection.timeout,
      useSSL: dbtConnection.useSSL,
      bypassSslCertCheck: dbtConnection.bypassSslCertCheck,
    };
  }

  // CS generateJdbcUrl (1351-1363)
  toJdbcUrl(conn: KineticaConnection): string {
    // Kinetica JDBC URL format: jdbc:kinetica:URL=http://<host>:9191
    // Optional parameters can be appended
    let kineticaUrl = `jdbc:kinetica:URL=${buildKineticaUrl(conn)}`;
    // Add additional params if needed (e.g., timeout)
    if (conn.timeout) {
      kineticaUrl += `;Timeout=${conn.timeout}`;
    }
    if (conn.bypassSslCertCheck && conn.useSSL) {
      kineticaUrl += ';BypassSslCertCheck=1';
    }
    return kineticaUrl;
  }
}
